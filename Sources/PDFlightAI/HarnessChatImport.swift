import CryptoKit
import Foundation
import PDFlightCore

/// Read-only preparation of Harness paper-chat archives for a native client.
/// The original archive is retained alongside each conversion so information
/// that does not fit the native message schema is never discarded.
public enum HarnessChatImport {
    public struct Conversation: Sendable {
        public let value: AIConversation
        public let sourceArchive: Data
        public let provider: String?
        public let model: String?
    }

    public struct Result: Sendable {
        public let paperID: String?
        public let activeSessionID: String?
        public let conversations: [Conversation]
        public let skippedSessionIDs: [String]
    }

    public enum ImportError: Error {
        case ambiguousPaper
        case invalidArchive(String)
    }

    /// The mapping is generated by the existing bridge and also survives a PDF
    /// being edited after its Harness library copy was made. Without a mapping,
    /// require both the original title and identical bytes before matching.
    public static func prepare(documentURL: URL, dataDirectory: URL, pathMappingsURL: URL?, recoveredArchivesDirectory: URL? = nil, projectionDirectory: URL? = nil) throws -> Result {
        let decoder = JSONDecoder()
        let indexURL = dataDirectory.appendingPathComponent("index.json")
        guard FileManager.default.fileExists(atPath: indexURL.path) else {
            return Result(paperID: nil, activeSessionID: nil, conversations: [], skippedSessionIDs: [])
        }
        let library = try decoder.decode(Library.self, from: Data(contentsOf: indexURL))
        let standardized = documentURL.standardizedFileURL.resolvingSymlinksInPath().path
        let direct = library.papers.filter {
            URL(fileURLWithPath: $0.path).standardizedFileURL.resolvingSymlinksInPath().path == standardized
        }
        guard direct.count <= 1 else { throw ImportError.ambiguousPaper }
        var paper: Paper? = direct.first
        if let pathMappingsURL, FileManager.default.fileExists(atPath: pathMappingsURL.path) {
            let mappings = try decoder.decode([String: String].self, from: Data(contentsOf: pathMappingsURL))
            if paper == nil, let id = mappings[standardized] { paper = library.papers.first { $0.id == id } }
        }
        if paper == nil {
            let sourceName = documentURL.deletingPathExtension().lastPathComponent.lowercased()
            let candidates = library.papers.filter {
                URL(fileURLWithPath: $0.title).deletingPathExtension().lastPathComponent.lowercased() == sourceName
            }
            if !candidates.isEmpty {
                let sourceDigest = try digest(documentURL)
                var matching: [Paper] = []
                for candidate in candidates {
                    guard let candidateDigest = try? digest(URL(fileURLWithPath: candidate.path)) else { continue }
                    if candidateDigest == sourceDigest { matching.append(candidate) }
                }
                guard matching.count <= 1 else { throw ImportError.ambiguousPaper }
                paper = matching.first
            }
        }
        guard let paper else {
            return Result(paperID: nil, activeSessionID: nil, conversations: [], skippedSessionIDs: [])
        }
        let groupsURL = dataDirectory.appendingPathComponent("conversations.json")
        let groups = try decoder.decode(Groups.self, from: Data(contentsOf: groupsURL))
        guard let group = groups.groups.first(where: { $0.paperId == paper.id }) else {
            return Result(paperID: paper.id, activeSessionID: nil, conversations: [], skippedSessionIDs: [])
        }
        var imported: [Conversation] = []
        var skipped: [String] = []
        for entry in group.conversations {
            // Never accept path separators or archive traversal from metadata.
            guard entry.sessionId.range(of: "^[A-Za-z0-9_-]+$", options: .regularExpression) != nil else {
                skipped.append(entry.sessionId); continue
            }
            var url = dataDirectory.appendingPathComponent("chats", isDirectory: true)
                .appendingPathComponent(entry.sessionId + ".json")
            if !FileManager.default.fileExists(atPath: url.path), let recoveredArchivesDirectory {
                url = recoveredArchivesDirectory.appendingPathComponent("chats", isDirectory: true)
                    .appendingPathComponent(entry.sessionId + ".json")
            }
            guard let raw = try? Data(contentsOf: url), let archive = try? decoder.decode(Archive.self, from: raw),
                  archive.sessionId == entry.sessionId, archive.paperId == paper.id,
                  archive.status != "deleted" else {
                skipped.append(entry.sessionId); continue
            }
            var messages: [AIChatMessage] = []
            var supported = true
            for item in archive.entries {
                guard let role = AIChatRole(rawValue: item.role), role != .system,
                      item.content.allSatisfy({ $0.type == "text" }) else { supported = false; break }
                let content = item.text ?? item.content.compactMap(\.text).joined()
                let date = item.time.map { Date(timeIntervalSince1970: $0 / 1_000) } ?? parseDate(archive.createdAt)
                messages.append(AIChatMessage(id: item.id, role: role, content: content, createdAt: date))
            }
            guard supported else { skipped.append(entry.sessionId); continue }
            let created = parseDate(archive.createdAt ?? entry.createdAt)
            let updated = parseDate(archive.updatedAt ?? archive.createdAt ?? entry.createdAt)
            let projection: ModelSelection? = projectionDirectory.flatMap { directory in
                guard let data = try? Data(contentsOf: directory.appendingPathComponent(entry.sessionId + ".json")),
                      let root = try? JSONDecoder().decode(Projection.self, from: data) else { return nil }
                return root.record.rows.modelSelection.val.pending ?? root.record.rows.modelSelection.val.lastUsed
            }
            let routeID = projection.flatMap { value in value.provider.flatMap { p in value.model.map { p + "/" + $0 } } }
                ?? archive.provider.flatMap { provider in archive.model.map { provider + "/" + $0 } }
            let sourceTitle = entry.title ?? archive.title ?? paper.title
            let name = sourceTitle.lowercased().hasSuffix(".pdf") ? String(sourceTitle.dropLast(4)) : sourceTitle
            let value = AIConversation(id: entry.sessionId, title: PaperLibraryPaper.automaticDisplayAlias(for: name),
                promptPreset: .reading, messages: messages, createdAt: created, updatedAt: updated,
                modelRouteID: routeID, webConversationKey: archive.web?.conversationKey, webConversationURL: archive.web?.url,
                reasoningEffort: projection?.reasoningEffort)
            imported.append(Conversation(value: value, sourceArchive: raw, provider: archive.provider, model: archive.model))
        }
        return Result(paperID: paper.id, activeSessionID: group.lastSessionId,
                      conversations: imported, skippedSessionIDs: skipped)
    }

    private static func digest(_ url: URL) throws -> SHA256.Digest {
        let handle = try FileHandle(forReadingFrom: url)
        defer { try? handle.close() }
        var hash = SHA256()
        while let bytes = try handle.read(upToCount: 1_048_576), !bytes.isEmpty { hash.update(data: bytes) }
        return hash.finalize()
    }

    private static func parseDate(_ value: String?) -> Date {
        guard let value else { return .distantPast }
        let formatter = ISO8601DateFormatter()
        formatter.formatOptions = [.withInternetDateTime, .withFractionalSeconds]
        if let date = formatter.date(from: value) { return date }
        formatter.formatOptions = [.withInternetDateTime]
        return formatter.date(from: value) ?? .distantPast
    }

    private struct Library: Decodable { let papers: [Paper] }
    private struct Paper: Decodable { let id: String; let title: String; let path: String }
    private struct Groups: Decodable { let groups: [Group] }
    private struct Group: Decodable {
        let paperId: String; let lastSessionId: String?; let conversations: [Membership]
    }
    private struct Membership: Decodable { let sessionId: String; let title: String?; let createdAt: String? }
    private struct Archive: Decodable {
        let sessionId: String; let paperId: String; let title: String?; let createdAt: String?
        let updatedAt: String?; let status: String?; let provider: String?; let model: String?
        let web: WebMetadata?
        let entries: [Entry]
    }
    private struct WebMetadata: Decodable { let conversationKey: String?; let url: String? }
    private struct Entry: Decodable {
        let id: String; let role: String; let text: String?; let time: Double?; let content: [Block]
    }
    private struct Block: Decodable { let type: String; let text: String? }
    private struct ModelSelection: Decodable { let provider: String?; let model: String?; let reasoningEffort: String? }
    private struct Projection: Decodable {
        struct Record: Decodable {
            struct Rows: Decodable {
                struct Field: Decodable {
                    struct Value: Decodable { let lastUsed: ModelSelection?; let pending: ModelSelection? }
                    let val: Value
                }
                let modelSelection: Field
            }
            let rows: Rows
        }
        let record: Record
    }
}
